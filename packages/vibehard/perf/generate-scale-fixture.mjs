const here = path.dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = path.resolve(here, "../../..");
const MARKER = ".vh-perf-generated";

export const DEFAULT_PARAMETERS = {
  shape: "selection",
  files: 1000,
  symbolsPerFile: 6,
  sharedFiles: 25,
  specFiles: 100,
  testsPerSpec: 10,
  touchedPerTest: 150,
  seed: 1,
  framework: "puppeteer",
};

function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function sample(rng, pool, count) {
  const copy = [...pool];
  const n = Math.min(count, copy.length);
  for (let i = 0; i < n; i += 1) {
    const j = i + Math.floor(rng() * (copy.length - i));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.slice(0, n);
}

function pad(value, width) {
  return String(value).padStart(width, "0");
}

function write(root, rel, text) {
  const file = path.join(root, rel);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, text);
}

function git(cwd, args) {
  const result = spawnSync("git", args, { cwd, encoding: "utf8" });
  if (result.status !== 0) {
    throw new Error(`git ${args.join(" ")} failed:\n${result.stderr || result.stdout}`);
  }
  return result.stdout;
}

function prepareOutput(outDir) {
  if (existsSync(outDir)) {
    if (!existsSync(path.join(outDir, MARKER))) {
      throw new Error(
        `refusing to overwrite ${outDir}: not a generated perf fixture (missing ${MARKER})`,
      );
    }
    rmSync(outDir, { recursive: true, force: true });
  }
  mkdirSync(outDir, { recursive: true });
  writeFileSync(path.join(outDir, MARKER), "generated by vibehard perf; safe to delete\n");
}

function moduleSource({ index, symbolsPerFile, sharedImport }) {
  const lines = [];
  if (sharedImport !== null) {
    lines.push(
      `import { fn0 as sharedFn, VALUE0 as SHARED_VALUE } from "../shared/${sharedImport}.js";`,
      "",
    );
  }
  for (let j = 0; j < symbolsPerFile; j += 1) {
    lines.push(`export const VALUE${j} = ${index * 100 + j};`);
  }
  lines.push("");
  for (let j = 0; j < symbolsPerFile; j += 1) {
    const shared = sharedImport !== null && j === 0 ? " + sharedFn(SHARED_VALUE)" : "";
    lines.push(
      `export function fn${j}(input: number): number {`,
      `  return input + VALUE${j}${shared};`,
      "}",
      "",
    );
  }
  lines.push(
    `export class Service${index} {`,
    "  run(input: number): number {",
    `    return fn0(input) + VALUE0;`,
    "  }",
    "}",
    "",
    `export const arrow${index} = (input: number): number => fn0(input);`,
    "",
    "export function runModule(input: number): number {",
    `  return ${Array.from({ length: symbolsPerFile }, (_, j) => `fn${j}(input)`).join(" + ")} + new Service${index}().run(input);`,
    "}",
    "",
  );
  return lines.join("\n");
}

function generateSources(root, params) {
  const sharedFiles = Math.min(params.sharedFiles, params.files);
  const moduleFiles = Math.max(0, params.files - sharedFiles);
  const sharedRels = [];
  for (let i = 0; i < sharedFiles; i += 1) {
    const rel = `src/shared/s${pad(i, 3)}.ts`;
    sharedRels.push(rel);
    write(
      root,
      rel,
      moduleSource({ index: i, symbolsPerFile: params.symbolsPerFile, sharedImport: null }),
    );
  }
  const moduleRels = [];
  for (let i = 0; i < moduleFiles; i += 1) {
    const rel = `src/modules/m${pad(i, 4)}.ts`;
    moduleRels.push(rel);
    const sharedImport = sharedFiles > 0 ? `s${pad(i % sharedFiles, 3)}` : null;
    write(
      root,
      rel,
      moduleSource({ index: i, symbolsPerFile: params.symbolsPerFile, sharedImport }),
    );
  }
  return { sharedRels, moduleRels };
}

const SUPPORT_GROUP_SIZE = 10;

function generateSpecs(root, params) {
  // Test-support helpers (Phase 5): every spec imports a shared helper
  // and its group's helper, so the `support` scenario can mutate one
  // group helper and expect exactly that group's specs to select.
  const playwright = params.framework === "playwright";
  const helperExt = playwright ? "ts" : "mjs";
  const helperSuffix = playwright ? "js" : "mjs";
  const groupCount = Math.max(1, Math.ceil(params.specFiles / SUPPORT_GROUP_SIZE));
  write(root, `e2e/support/shared.${helperExt}`, `export const sharedSupport = "shared";\n`);
  for (let g = 0; g < groupCount; g += 1) {
    write(
      root,
      `e2e/support/group-${pad(g, 3)}.${helperExt}`,
      `export const groupSupport${g} = "group-${g}";\n`,
    );
  }
  const supportGroup = groupCount > 1 ? 1 : 0;
  const support = {
    file: `e2e/support/group-${pad(supportGroup, 3)}.${helperExt}`,
    specFiles: [],
  };

  for (let s = 0; s < params.specFiles; s += 1) {
    const group = Math.floor(s / SUPPORT_GROUP_SIZE);
    const lines = [];
    const supportImports = [
      `import { sharedSupport } from "./support/shared.${helperSuffix}";`,
      `import { groupSupport${group} } from "./support/group-${pad(group, 3)}.${helperSuffix}";`,
      `void sharedSupport;`,
      `void groupSupport${group};`,
      "",
    ];
    if (params.framework === "playwright") {
      lines.push(`import { test } from "vibehard/playwright";`, ...supportImports);
      for (let t = 0; t < params.testsPerSpec; t += 1) {
        const n = s * params.testsPerSpec + t;
        lines.push(
          `test("generated test ${pad(n, 6)}", async () => {`,
          "  // Selection benchmark only; recording uses --shape recordable.",
          "});",
          "",
        );
      }
      write(root, `e2e/spec${pad(s, 3)}.spec.ts`, lines.join("\n"));
      if (group === supportGroup) support.specFiles.push(`e2e/spec${pad(s, 3)}.spec.ts`);
    } else {
      lines.push(`import { describeTest } from "vibehard/puppeteer";`, ...supportImports);
      for (let t = 0; t < params.testsPerSpec; t += 1) {
        const n = s * params.testsPerSpec + t;
        lines.push(
          `describeTest("generated test ${pad(n, 6)}", async () => {`,
          "  // Selection benchmark only; recording uses --shape recordable.",
          "});",
          "",
        );
      }
      write(root, `e2e/spec${pad(s, 3)}.test.mjs`, lines.join("\n"));
      if (group === supportGroup) support.specFiles.push(`e2e/spec${pad(s, 3)}.test.mjs`);
    }
  }
  return support;
}

